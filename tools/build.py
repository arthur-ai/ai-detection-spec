#!/usr/bin/env python3
"""Compose queries/*.sql into the two artifacts in dist/.

Authoring happens in one file per domain; shipping happens as one query. That split
exists for a measured reason: osqueryi costs about 0.47s to start, so running the
branches as separate processes costs roughly 29% more wall clock, and a Jamf Extension
Attribute has a timeout to respect. Composing at build time keeps the runtime shape
unchanged while letting the source be readable.

    dist/discovery.sql       every `fast` and `slow` query, joined with UNION ALL
    dist/discovery-deep.sql  every `expensive` query, joined the same way
    dist/ai-discovery.conf   an osquery pack, one named query per file

`expensive` queries are excluded from discovery.sql and composed into discovery-deep.sql
instead. THE SPLIT IS THE WHOLE POINT AND IT IS NOT COSMETIC: an expensive query is one
that can block forever -- `docker_images` against a daemon that accepts and never answers
does not return at all -- and the only bound available is a wall-clock kill on the osqueryi
process. There is no osquery flag for it (checked on 5.23.1: --docker_socket is the only
docker flag, --alarm_timeout is shutdown-only, --schedule_timeout is osqueryd's schedule).
A kill is per PROCESS, and what that costs with the branch inline is not what you would
guess -- queries/containers.sql records the measurement. Short version: the composed file
cannot bound itself, and bounding it from outside returns a full-looking inventory that
exits 0 while silently omitting the container half. bin/discover --deep runs the two
artifacts as two processes and unions the rows.

No dependencies. Run: python3 tools/build.py [--check]
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
QUERIES, DIST = ROOT / "queries", ROOT / "dist"
COLUMNS = ["kind", "id", "ver", "loc", "extra", "perms"]

BANNER = """-- GENERATED by tools/build.py. Do not edit.
-- Source of truth is queries/*.sql; edit there and rebuild.
-- Columns, in order: {columns}
"""

# The deep artifact's banner carries three warnings, because every one of them has a
# failure behind it. A SUPPLEMENT that reads like a superset is the trap: this repo has
# already shipped a pack whose queries silently returned zero rows, and zero rows is what
# a clean Mac returns, so it looked like it worked.
DEEP_BANNER = """-- GENERATED by tools/build.py. Do not edit.
-- Source of truth is queries/*.sql; edit there and rebuild.
-- Columns, in order: {columns}
--
-- SUPPLEMENT, NOT A SUPERSET. This file holds the `expensive` queries and nothing else.
-- Union its rows with dist/discovery.sql downstream; run it alone and you have described
-- a Mac with no applications on it.
--
-- EVERY QUERY IN HERE CAN BLOCK FOREVER. `docker_images` against a daemon that accepts
-- the connection and never answers does not return -- Docker Desktop mid-startup, or
-- installed and not opened today. osquery has no timeout for it, so the only bound is a
-- wall-clock kill on this process. Run it behind a health guard AND that kill:
-- `bin/discover --deep` does both, and bin/container-scan is the guard.
--
-- DO NOT PASTE THESE BRANCHES INTO dist/discovery.sql. A kill is per process, and that
-- file is one process over one statement. Bounding it there was MEASURED, and the result is
-- worse than losing rows: all 757 other rows come back and osqueryi exits 0, so the answer
-- looks complete while the container half was never read -- and 6 of an Extension
-- Attribute's 10 seconds went to a daemon that answered nothing. Unbounded, the whole
-- inventory value blanks instead. The split is what makes the bound apply to the branch
-- that needs it.
"""


def compose(banner, parts):
    """One statement, the branches joined with UNION ALL, under the given banner."""
    return (banner.format(columns=", ".join(COLUMNS)) + "\n"
            + "\n\nUNION ALL\n\n".join(parts) + ";\n")


def flatten(sql):
    """Collapse SQL to one line for the pack, dropping -- comments first.

    THE ORDER MATTERS AND IS THE WHOLE POINT. A `--` comment runs to end of LINE, so
    flattening first and stripping never turns the first comment into a muzzle over
    everything after it. That shipped: four of the five pack queries returned zero rows,
    with no error, because the flattened string commented itself out after the first
    branch. Zero rows is what a clean Mac returns, so the pack looked like it worked.

    Quote-aware, because a literal could contain a double dash. None do today; a
    stripper that assumed so would be a trap for whoever adds one.
    """
    out, in_string, i = [], False, 0
    while i < len(sql):
        ch = sql[i]
        if in_string:
            out.append(ch)
            if ch == "'":
                in_string = sql[i + 1:i + 2] == "'"   # '' is an escaped quote
                if in_string:
                    out.append("'")
                    i += 1
            i += 1
            continue
        if ch == "'":
            in_string = True
            out.append(ch)
            i += 1
            continue
        if sql.startswith("--", i):
            while i < len(sql) and sql[i] != "\n":
                i += 1
            continue
        out.append(ch)
        i += 1
    flat = " ".join("".join(out).split())
    if "--" in flat:
        sys.exit(f"flatten left a comment in: {flat[:120]}")
    return flat


def frontmatter(text, path):
    """Read the `-- key: value` header. Absent keys are an error, not a default:
    a query with no declared cost silently escapes the performance gate."""
    fm = dict(re.findall(r"^--\s*([a-z-]+):\s*(.+?)\s*$", text, re.M))
    for key in ("name", "description", "cost", "platform"):
        if key not in fm:
            sys.exit(f"{path.name}: missing '-- {key}:' in frontmatter")
    if fm["cost"] not in ("fast", "slow", "expensive"):
        sys.exit(f"{path.name}: cost must be fast, slow or expensive, got {fm['cost']!r}")
    return fm


def body(text):
    """Everything that is not a leading frontmatter line."""
    lines = text.splitlines()
    start = 0
    for i, line in enumerate(lines):
        if line.strip() and not line.lstrip().startswith("--"):
            start = i
            break
    text = "\n".join(lines[start:]).strip()
    # A trailing semicolon here would end the composed query early and silently turn
    # the remainder into a second statement. osqueryi then emits two JSON documents
    # and every downstream parser sees only the first.
    return text.rstrip().rstrip(";").rstrip()


def main():
    check = "--check" in sys.argv
    files = sorted(QUERIES.glob("*.sql"))
    if not files:
        sys.exit("no queries found")

    inline, deep, pack = [], [], {}
    for path in files:
        text = path.read_text()
        fm = frontmatter(text, path)
        sql = body(text)
        pack[fm["name"]] = {
            "query": flatten(sql).rstrip(";") + ";",
            "interval": 3600,
            "platform": fm["platform"],
            "description": fm["description"],
        }
        if fm["cost"] == "expensive":
            print(f"  {path.name}: expensive, deep artifact only")
            deep.append(f"-- from {path.name}\n{sql}")
            continue
        inline.append(f"-- from {path.name}\n{sql}")

    composed = compose(BANNER, inline)
    conf = json.dumps({"queries": pack}, indent=2, sort_keys=True) + "\n"

    targets = {DIST / "discovery.sql": composed, DIST / "ai-discovery.conf": conf}

    # An empty deep artifact is NOT written. A file containing only a banner is not valid
    # SQL, and `osqueryi --json < banner-only-file` fails in a way that reads like a broken
    # install rather than like "there is nothing expensive to run". Absent is unambiguous,
    # and bin/discover --deep says so plainly. Any stale copy is removed below, and --check
    # treats a leftover as the drift it is.
    deep_path = DIST / "discovery-deep.sql"
    if deep:
        targets[deep_path] = compose(DEEP_BANNER, deep)
    if check:
        # A generated artifact that has drifted from its source is worse than no
        # generated artifact: consumers take dist/ at face value.
        stale = [p.name for p, want in targets.items()
                 if not p.exists() or p.read_text() != want]
        if not deep and deep_path.exists():
            stale.append(f"{deep_path.name} exists but no query declares itself expensive")
        if stale:
            sys.exit(f"dist/ is stale: {', '.join(stale)}. Run tools/build.py.")
        print("dist/ is up to date")
        return

    DIST.mkdir(exist_ok=True)
    if not deep and deep_path.exists():
        deep_path.unlink()
        print(f"  removed {deep_path.relative_to(ROOT)} (nothing is expensive any more)")
    for path, content in targets.items():
        path.write_text(content)
        print(f"  wrote {path.relative_to(ROOT)} ({len(content.splitlines())} lines)")


if __name__ == "__main__":
    main()
