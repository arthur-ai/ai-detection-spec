#!/usr/bin/env python3
"""Compose queries/*.sql into the two artifacts in dist/.

Authoring happens in one file per domain; shipping happens as one query. That split
exists for a measured reason: osqueryi costs about 0.47s to start, so running the
branches as separate processes costs roughly 29% more wall clock, and a synchronous
reporting path has a budget to respect. Composing at build time keeps the runtime shape
unchanged while letting the source be readable.

    dist/discovery-darwin.sql  every macOS `fast`/`slow` query, joined with UNION ALL
    dist/discovery-linux.sql   the same for Linux -- a DIFFERENT set of tables, not a subset
    dist/discovery-deep.sql    every `expensive` query, joined the same way
    dist/ai-discovery.conf     an osquery pack, one named query per file

Four more files in dist/ are RENDERED from the catalog rather than composed from queries/,
by tools/render_match.py: the signature fragment, the per-platform match queries and the
Fleet policies. That tool needs PyYAML and this one must not, so main() runs it when it can
and otherwise says what is left to do; `render_match.py --check` is its own gate.

ONE COMPOSED ARTIFACT PER PLATFORM, because one file cannot span two: the tables are
disjoint, so a Linux artifact on macOS dies on the first table and returns "[\n\n]" --
valid, empty, plausible JSON -- with exit 1. A query declares `-- platform: darwin`,
`linux` or `posix`, and `posix` lands in both.

`expensive` queries are excluded from discovery.sql and composed into discovery-deep.sql
instead. THE SPLIT IS THE WHOLE POINT AND IT IS NOT COSMETIC: an expensive query is one
that can block forever -- `docker_images` against a daemon that accepts and never answers
does not return at all -- and the only bound available is a wall-clock kill on the osqueryi
process. There is no osquery flag for it (checked on 5.23.1: --docker_socket is the only
docker flag, --alarm_timeout is shutdown-only, --schedule_timeout is osqueryd's schedule).
A kill is per PROCESS, and what that costs with the branch inline is not what you would
guess -- queries/containers.sql records the measurement. Short version: the composed file
cannot bound itself, and bounding it from outside returns a full-looking inventory that
exits 0 while silently omitting the container half. bin/discover --deep runs the two
artifacts as two processes and unions the rows.

No dependencies. Run: python3 tools/build.py [--check]
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
QUERIES, DIST = ROOT / "queries", ROOT / "dist"
COLUMNS = ["kind", "id", "ver", "loc", "extra", "perms"]

BANNER = """-- GENERATED by tools/build.py. Do not edit.
-- Source of truth is queries/*.sql; edit there and rebuild.
-- Columns, in order: {columns}
"""

# ONE PLATFORM PER ARTIFACT, said in the file itself, because the failure of running the
# wrong one is silent-shaped: a Linux artifact on macOS dies on the first missing table
# and prints a valid empty JSON array.
PLATFORM_NOTE = """--
-- PLATFORM: {platform}. Run this only on {platform}. The tables named here do not all
-- exist elsewhere, and osqueryi given a missing table returns "[\\n\\n]" -- valid,
-- empty, entirely plausible JSON -- and exits 1. Every other artifact in dist/ is for a
-- different platform and is NOT a superset of this one. bin/discover picks by `uname -s`.
"""

# The deep artifact's banner carries three warnings, because every one of them has a
# failure behind it. A SUPPLEMENT that reads like a superset is the trap: this repo has
# already shipped a pack whose queries silently returned zero rows, and zero rows is what
# a clean Mac returns, so it looked like it worked.
DEEP_BANNER = """-- GENERATED by tools/build.py. Do not edit.
-- Source of truth is queries/*.sql; edit there and rebuild.
-- Columns, in order: {columns}
--
-- SUPPLEMENT, NOT A SUPERSET. This file holds the `expensive` queries and nothing else.
-- Union its rows with dist/discovery-<platform>.sql downstream; run it alone and you have
-- described a machine with no applications on it.
--
-- EVERY QUERY IN HERE CAN BLOCK FOREVER. `docker_images` against a daemon that accepts
-- the connection and never answers does not return -- Docker Desktop mid-startup, or
-- installed and not opened today. osquery has no timeout for it, so the only bound is a
-- wall-clock kill on this process. Run it behind a health guard AND that kill:
-- `bin/discover --deep` does both, and bin/container-scan is the guard.
--
-- DO NOT PASTE THESE BRANCHES INTO dist/discovery-<platform>.sql. A kill is per process,
-- and that file is one process over one statement. Bounding it there was MEASURED, and the result is
-- worse than losing rows: all 757 other rows come back and osqueryi exits 0, so the answer
-- looks complete while the container half was never read -- and 6 of an Extension
-- Attribute's 10 seconds went to a daemon that answered nothing. Unbounded, the whole
-- inventory value blanks instead. The split is what makes the bound apply to the branch
-- that needs it.
"""


def compose(banner, parts):
    """One statement, the branches joined with UNION ALL, under the given banner."""
    return (banner.format(columns=", ".join(COLUMNS)) + "\n"
            + "\n\nUNION ALL\n\n".join(parts) + ";\n")


def flatten(sql):
    """Collapse SQL to one line for the pack, dropping -- comments first.

    THE ORDER MATTERS AND IS THE WHOLE POINT. A `--` comment runs to end of LINE, so
    flattening first and stripping never turns the first comment into a muzzle over
    everything after it. That shipped: four of the five pack queries returned zero rows,
    with no error, because the flattened string commented itself out after the first
    branch. Zero rows is what a clean Mac returns, so the pack looked like it worked.

    Quote-aware, because a literal could contain a double dash. None do today; a
    stripper that assumed so would be a trap for whoever adds one.
    """
    out, in_string, i = [], False, 0
    while i < len(sql):
        ch = sql[i]
        if in_string:
            out.append(ch)
            if ch == "'":
                in_string = sql[i + 1:i + 2] == "'"   # '' is an escaped quote
                if in_string:
                    out.append("'")
                    i += 1
            i += 1
            continue
        if ch == "'":
            in_string = True
            out.append(ch)
            i += 1
            continue
        if sql.startswith("--", i):
            while i < len(sql) and sql[i] != "\n":
                i += 1
            continue
        out.append(ch)
        i += 1
    flat = " ".join("".join(out).split())
    if "--" in flat:
        sys.exit(f"flatten left a comment in: {flat[:120]}")
    return flat


def platform_vocabulary():
    """The legal `-- platform:` values, from catalog/routes.yaml.

    One vocabulary for the whole repo: a route's platform and a query's platform are the
    same words, so they cannot drift into needing a translation table.
    """
    reg = ROOT / "catalog" / "routes.yaml"
    if not reg.exists():
        sys.exit(f"{reg} is missing; it is the route registry every tool reads")
    # Read WITHOUT PyYAML. tools/build.py has never had a dependency and the endpoint
    # path must stay that way -- `pip install pyyaml` is a requirement of the catalog
    # tools, not of composing SQL. Two flat top-level lists are all that is needed here.
    text = reg.read_text()
    plats = re.search(r"^platforms:\s*\[(.+?)\]\s*$", text, re.M)
    if not plats:
        sys.exit("catalog/routes.yaml: could not read the `platforms:` list")
    names = [p.strip() for p in plats.group(1).split(",") if p.strip()]
    groups = dict(re.findall(r"^  ([a-z]+):\s*\[(.+?)\]\s*$",
                             text.split("platform_groups:", 1)[-1], re.M))
    expand = {g: [p.strip() for p in v.split(",") if p.strip()] for g, v in groups.items()}
    return names, expand


PLATFORMS, PLATFORM_GROUPS = platform_vocabulary()


def frontmatter(text, path):
    """Read the `-- key: value` header. Absent keys are an error, not a default:
    a query with no declared cost silently escapes the performance gate.

    THE HEADER ONLY, NOT THE WHOLE FILE. This used to scan every line with re.M and
    dict() the result, so the LAST occurrence won -- and three files already leak stray
    keys out of their body comments (`browser.sql` yields `that`; `containers.sql` yields
    `measured` and `can`). Harmless only because none of them collided with a real key. A
    body comment reading `-- platform: linux is why ...` would have silently overridden
    the file's own header and produced a query osqueryd never schedules.
    """
    head = []
    for line in text.splitlines():
        if line.strip() and not line.lstrip().startswith("--"):
            break
        head.append(line)
    fm = dict(re.findall(r"^--\s*([a-z-]+):\s*(.+?)\s*$", "\n".join(head), re.M))
    for key in ("name", "description", "cost", "platform"):
        if key not in fm:
            sys.exit(f"{path.name}: missing '-- {key}:' in frontmatter")
    if fm["cost"] not in ("fast", "slow", "expensive"):
        sys.exit(f"{path.name}: cost must be fast, slow or expensive, got {fm['cost']!r}")
    # THE VALUE IS CHECKED NOW. It never was, so `-- platform: macos` built clean and
    # shipped a pack query osqueryd silently never scheduled -- zero rows, no error, and
    # zero rows is what a clean machine returns.
    if fm["platform"] not in PLATFORMS and fm["platform"] not in PLATFORM_GROUPS:
        sys.exit(f"{path.name}: platform must be one of "
                 f"{sorted(PLATFORMS) + sorted(PLATFORM_GROUPS)}, "
                 f"got {fm['platform']!r}")
    return fm


def platforms_of(fm):
    """The concrete platforms a query runs on. `posix` is darwin AND linux."""
    return PLATFORM_GROUPS.get(fm["platform"], [fm["platform"]])


def body(text):
    """Everything that is not a leading frontmatter line."""
    lines = text.splitlines()
    start = 0
    for i, line in enumerate(lines):
        if line.strip() and not line.lstrip().startswith("--"):
            start = i
            break
    text = "\n".join(lines[start:]).strip()
    # A trailing semicolon here would end the composed query early and silently turn
    # the remainder into a second statement. osqueryi then emits two JSON documents
    # and every downstream parser sees only the first.
    return text.rstrip().rstrip(";").rstrip()


def kinds_of(sql):
    """The row kinds a query emits, by the rule test/lint.sh already applies: every
    `SELECT '<kind>'` literal. tools/render_match.py picks the branches a per-agent
    Fleet policy needs by these, so the rule lives here once rather than twice."""
    return sorted(set(re.findall(r"SELECT\s+'(\w+)'", sql)))


def queries(files=None):
    """Every query file, read once: its frontmatter, its body, the platforms it runs on
    and the kinds it emits. main() composes dist/ from this; tools/render_match.py wraps
    the same bodies in a match, so the two can never read a file differently."""
    files = sorted(QUERIES.glob("*.sql")) if files is None else files
    if not files:
        sys.exit("no queries found")
    out = []
    for path in files:
        text = path.read_text()
        fm = frontmatter(text, path)
        sql = body(text)
        out.append({"path": path, "fm": fm, "sql": sql,
                    "platforms": platforms_of(fm), "kinds": kinds_of(sql),
                    "expensive": fm["cost"] == "expensive"})
    return out


def main():
    check = "--check" in sys.argv

    # PER PLATFORM, because one composed file cannot span two.
    #
    # dist/discovery.sql was a single UNION ALL over `FROM apps`. Fed to Linux osqueryi it
    # fails on the first table and returns "[\n\n]" with exit 1 -- five bytes of valid,
    # empty, entirely plausible JSON, which is this repo's canonical wrong answer. There
    # is no arrangement of one file that runs on both: the tables are disjoint by
    # construction. So `platform` now decides which artifact a query lands in, and a
    # `posix` query lands in both.
    inline, deep, pack = {}, [], {}
    for q in queries():
        path, fm, sql = q["path"], q["fm"], q["sql"]
        pack[fm["name"]] = {
            "query": flatten(sql).rstrip(";") + ";",
            "interval": 3600,
            "platform": fm["platform"],
            "description": fm["description"],
        }
        part = f"-- from {path.name}\n{sql}"
        if q["expensive"]:
            # ONE DEEP ARTIFACT, while every expensive query is portable -- and a loud
            # failure the day one is not, rather than a quiet guess about which platform
            # a shared file belongs to. containers.sql selects only from docker_images,
            # which specs/posix provides on both platforms, so two per-platform deep
            # files would be two identical files.
            if sorted(platforms_of(fm)) != sorted(PLATFORM_GROUPS.get("posix", [])):
                sys.exit(f"{path.name}: an `expensive` query must be `platform: posix` "
                         f"while dist/discovery-deep.sql is a single shared artifact, and "
                         f"this one declares {fm['platform']!r}. Either widen it or split "
                         f"the deep artifact per platform -- do not let one file stand in "
                         f"for a platform it cannot run on.")
            print(f"  {path.name}: expensive, deep artifact only")
            deep.append(part)
            continue
        for plat in q["platforms"]:
            inline.setdefault(plat, []).append(part)

    conf = json.dumps({"queries": pack}, indent=2, sort_keys=True) + "\n"
    targets = {DIST / "ai-discovery.conf": conf}
    for plat, parts in sorted(inline.items()):
        targets[DIST / f"discovery-{plat}.sql"] = compose(BANNER.format(
            columns=", ".join(COLUMNS)) + PLATFORM_NOTE.format(platform=plat), parts)

    # An empty deep artifact is NOT written. A file containing only a banner is not valid
    # SQL, and `osqueryi --json < banner-only-file` fails in a way that reads like a broken
    # install rather than like "there is nothing expensive to run". Absent is unambiguous,
    # and bin/discover --deep says so plainly. Any stale copy is removed below, and --check
    # treats a leftover as the drift it is.
    deep_path = DIST / "discovery-deep.sql"
    if deep:
        targets[deep_path] = compose(DEEP_BANNER, deep)

    # dist/discovery.sql IS GONE, and a leftover copy is drift rather than compatibility.
    # It was the unqualified name for what was only ever the macOS artifact; keeping it as
    # a copy of discovery-darwin.sql would mean the one file whose name makes no claim is
    # the one that silently makes the biggest.
    retired = [DIST / "discovery.sql"]

    # THE OTHER GENERATOR'S FILES ARE KNOWN HERE AND NOT CHECKED HERE. tools/render_match.py
    # renders the catalog into match SQL beside these artifacts; it needs PyYAML and this
    # file must not, so it keeps its own --check and this one only learns the names --
    # otherwise the unknown-file check below would call every rendered file drift. Imported
    # inside main() because render_match imports this module: at module scope the two
    # would import each other before either had finished defining anything.
    import render_match
    rendered = set(render_match.OUTPUTS)

    if check:
        # A generated artifact that has drifted from its source is worse than no
        # generated artifact: consumers take dist/ at face value.
        stale = [p.name for p, want in targets.items()
                 if not p.exists() or p.read_text() != want]
        if not deep and deep_path.exists():
            stale.append(f"{deep_path.name} exists but no query declares itself expensive")
        stale += [f"{p.name} is retired and should be deleted" for p in retired
                  if p.exists()]
        # A file in dist/ that nothing generates is the other direction of the same drift.
        known = {p.name for p in targets} | {deep_path.name} | rendered
        stale += [f"{p.name} is in dist/ but nothing generates it"
                  for p in sorted(DIST.glob("*")) if p.name not in known
                  and p not in retired]
        if stale:
            sys.exit(f"dist/ is stale: {', '.join(stale)}. Run tools/build.py.")
        print(f"dist/ is up to date ({len(targets)} artifacts, "
              f"platforms: {', '.join(sorted(inline))}; "
              f"{len(rendered)} rendered files are tools/render_match.py --check's)")
        return

    DIST.mkdir(exist_ok=True)
    if not deep and deep_path.exists():
        deep_path.unlink()
        print(f"  removed {deep_path.relative_to(ROOT)} (nothing is expensive any more)")
    for path in retired:
        if path.exists():
            path.unlink()
            print(f"  removed {path.relative_to(ROOT)} (retired: it named one platform "
                  f"while claiming none)")
    for path, content in targets.items():
        path.write_text(content)
        print(f"  wrote {path.relative_to(ROOT)} ({len(content.splitlines())} lines)")
    # Rendered in the same run when the catalog can be read, so one command leaves dist/
    # whole. Without PyYAML the enumeration still builds and the message says what is
    # left to do rather than pretending the rendered files were refreshed.
    try:
        import yaml  # noqa: F401  -- the probe, not a use
    except ImportError:
        print("  NOT regenerated: dist/signatures.sql and the other rendered files need "
              "PyYAML. Run tools/render_match.py where it is installed.")
        return
    render_match.write()


if __name__ == "__main__":
    main()
