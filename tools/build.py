#!/usr/bin/env python3
"""Compose queries/*.sql into the two artifacts in dist/.

Authoring happens in one file per domain; shipping happens as one query. That split
exists for a measured reason: osqueryi costs about 0.47s to start, so running the
branches as separate processes costs roughly 29% more wall clock, and a Jamf Extension
Attribute has a timeout to respect. Composing at build time keeps the runtime shape
unchanged while letting the source be readable.

    dist/discovery.sql       every `fast` and `slow` query, joined with UNION ALL
    dist/discovery-deep.sql  every `expensive` query, joined the same way
    dist/ai-discovery.conf   an osquery pack, one named query per file
    dist/jamf-collect.sh     one self-contained file, carrying the runner and the queries
                             as an embedded payload, for an MDM that hosts a script but
                             cannot place files. NO PACKAGE, no signing, no notarization.

`expensive` queries are excluded from discovery.sql and composed into discovery-deep.sql
instead. THE SPLIT IS THE WHOLE POINT AND IT IS NOT COSMETIC: an expensive query is one
that can block forever -- `docker_images` against a daemon that accepts and never answers
does not return at all -- and the only bound available is a wall-clock kill on the osqueryi
process. There is no osquery flag for it (checked on 5.23.1: --docker_socket is the only
docker flag, --alarm_timeout is shutdown-only, --schedule_timeout is osqueryd's schedule).
A kill is per PROCESS, and what that costs with the branch inline is not what you would
guess -- queries/containers.sql records the measurement. Short version: the composed file
cannot bound itself, and bounding it from outside returns a full-looking inventory that
exits 0 while silently omitting the container half. bin/discover --deep runs the two
artifacts as two processes and unions the rows.

No dependencies. Run: python3 tools/build.py [--check]
"""
import base64
import gzip
import io
import json
import pathlib
import re
import sys
import tarfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
QUERIES, DIST = ROOT / "queries", ROOT / "dist"
COLUMNS = ["kind", "id", "ver", "loc", "extra", "perms"]

BANNER = """-- GENERATED by tools/build.py. Do not edit.
-- Source of truth is queries/*.sql; edit there and rebuild.
-- Columns, in order: {columns}
"""

# The deep artifact's banner carries three warnings, because every one of them has a
# failure behind it. A SUPPLEMENT that reads like a superset is the trap: this repo has
# already shipped a pack whose queries silently returned zero rows, and zero rows is what
# a clean Mac returns, so it looked like it worked.
DEEP_BANNER = """-- GENERATED by tools/build.py. Do not edit.
-- Source of truth is queries/*.sql; edit there and rebuild.
-- Columns, in order: {columns}
--
-- SUPPLEMENT, NOT A SUPERSET. This file holds the `expensive` queries and nothing else.
-- Union its rows with dist/discovery.sql downstream; run it alone and you have described
-- a Mac with no applications on it.
--
-- EVERY QUERY IN HERE CAN BLOCK FOREVER. `docker_images` against a daemon that accepts
-- the connection and never answers does not return -- Docker Desktop mid-startup, or
-- installed and not opened today. osquery has no timeout for it, so the only bound is a
-- wall-clock kill on this process. Run it behind a health guard AND that kill:
-- `bin/discover --deep` does both, and bin/container-scan is the guard.
--
-- DO NOT PASTE THESE BRANCHES INTO dist/discovery.sql. A kill is per process, and that
-- file is one process over one statement. Bounding it there was MEASURED, and the result is
-- worse than losing rows: all 757 other rows come back and osqueryi exits 0, so the answer
-- looks complete while the container half was never read -- and 6 of an Extension
-- Attribute's 10 seconds went to a daemon that answered nothing. Unbounded, the whole
-- inventory value blanks instead. The split is what makes the bound apply to the branch
-- that needs it.
"""


# The self-contained collector. Jamf hosts a Script and runs it from a Policy trigger, which
# supplies the scheduling; what it cannot do is place the query artifacts on disk -- and that,
# not the scheduling, is the only reason a package was ever needed. Embedding them removes it,
# and with it code signing, notarization and a PPPC profile.
#
# THE PAYLOAD IS THE REAL bin/ AND dist/, not a copy with the SQL pasted in. A second
# implementation of the runner would drift from the first, and this repo has already shipped
# one silent drift: the pack's browser query. Extract, run, delete.
COLLECTOR = r"""#!/bin/bash
# GENERATED by tools/build.py. Do not edit; rebuild.
#
# Self-contained AI inventory collector. Add this file to Jamf Pro under Settings > Computer
# Management > Scripts, then run it from a Policy on a recurring trigger. It writes three
# files an Extension Attribute reads with `cat`:
#
#   $OUT/inventory.json   the readable payload
#   $OUT/inventory.ea     the framed value to report, ~18KB of a ~30KB cap
#   $OUT/status.txt       one line, for a Smart Group to match on
#
# Needs osquery and python3. INSTALLS NOTHING: the embedded payload is extracted to a private
# temp directory, run, and deleted. Override the output directory with ARTHUR_OUT_DIR.
#
# WHY A SCHEDULED SCRIPT AND NOT AN EXTENSION ATTRIBUTE. osquery's docker_images has no
# timeout of its own, and against a daemon that answers /_ping and then stops serving, the
# query does not return. No documented Jamf timeout for an EA script exists, so an unbounded
# EA does not fail fast -- it hangs that Mac's inventory collection. Nothing waits on a Policy.
set -uo pipefail

OUT="${ARTHUR_OUT_DIR:-/var/lib/arthur}"

# TMPDIR is not guaranteed for a Jamf-run script, and /var/tmp outlives a cleared /tmp.
work="$(mktemp -d "${TMPDIR:-/var/tmp}/arthur-collect.XXXXXX")" || {
  echo "arthur: cannot create a working directory" >&2; exit 1; }
trap 'rm -rf "$work"' EXIT HUP INT TERM

cat > "$work/payload.b64" <<'ARTHUR_PAYLOAD_EOF'
@PAYLOAD@
ARTHUR_PAYLOAD_EOF

# BSD base64 decodes with -D, GNU with -d. From a file rather than a pipe, so the fallback
# can retry: a consumed pipe cannot be read twice.
base64 -D -i "$work/payload.b64" -o "$work/payload.tgz" 2>/dev/null \
  || base64 -d "$work/payload.b64" > "$work/payload.tgz" 2>/dev/null \
  || { echo "arthur: could not decode the embedded payload" >&2; exit 1; }

tar -xzf "$work/payload.tgz" -C "$work" || {
  echo "arthur: could not unpack the embedded payload" >&2; exit 1; }
chmod +x "$work/bin/"* 2>/dev/null

mkdir -p "$OUT" 2>/dev/null || { echo "arthur: cannot create $OUT" >&2; exit 1; }

# Writes by rename, so a reader catching this mid-run sees the previous complete file rather
# than a truncated one.
"$work/bin/discover" \
  --write  "$OUT/inventory.json" \
  --framed "$OUT/inventory.ea" \
  --status "$OUT/status.txt" > /dev/null

# Jamf records a script's exit status and shows a non-zero one as a failed Policy. A branch
# that could not look is NOT a failed collection -- the payload says so per branch, and the
# status file is what a Smart Group reads. Only an actual inability to collect is an error.
[ -s "$OUT/status.txt" ] || { echo "arthur: no status written" >&2; exit 1; }
cat "$OUT/status.txt"
exit 0
"""


# ONLY WHAT THE COLLECTOR RUNS. bin/classify is deliberately absent: classification happens
# server-side, the collector never invokes it, and a payload carrying code it does not run is
# a bigger file and a wider blast radius for no benefit.
PAYLOAD_FILES = ("bin/discover", "bin/container-scan",
                 "dist/discovery.sql", "dist/discovery-deep.sql", "dist/ai-discovery.conf")

PAYLOAD_MARKER = "ARTHUR_PAYLOAD_EOF"


def payload_tar(root):
    """The embedded payload, as tar bytes. BYTE-REPRODUCIBLE ACROSS MACHINES, which the
    compressed form is not: tar records mtimes, uids, modes and entry order, and every one of
    them is pinned here."""
    raw = io.BytesIO()
    with tarfile.open(fileobj=raw, mode="w") as tar:
        for rel in sorted(PAYLOAD_FILES):
            path = root / rel
            if not path.is_file():
                sys.exit(f"collector payload: {rel} is missing")
            info = tar.gettarinfo(str(path), arcname=rel)
            info.mtime, info.uid, info.gid = 0, 0, 0
            info.uname = info.gname = ""
            info.mode = 0o755 if rel.startswith("bin/") else 0o644
            with path.open("rb") as fh:
                tar.addfile(info, fh)
    return raw.getvalue()


def collector(root):
    """One shell file carrying the payload as base64 of gzip of that tar."""
    b64 = base64.b64encode(gzip.compress(payload_tar(root), 9, mtime=0)).decode()
    wrapped = "\n".join(b64[i:i + 76] for i in range(0, len(b64), 76))
    return COLLECTOR.replace("@PAYLOAD@", wrapped)


PAYLOAD_OPEN = "<<'" + PAYLOAD_MARKER + "'\n"
PAYLOAD_CLOSE = "\n" + PAYLOAD_MARKER + "\n"


def _split_collector(text):
    """(wrapper before the payload, the base64 body, wrapper after it)."""
    open_at = text.index(PAYLOAD_OPEN) + len(PAYLOAD_OPEN)
    close_at = text.index(PAYLOAD_CLOSE, open_at)
    return text[:open_at], text[open_at:close_at], text[close_at:]


def collector_matches(text, root):
    """Does an existing collector carry this tree?

    COMPARED BY MEANING, NOT BY BYTES, and the difference is not pedantry: zlib's output is
    not identical across zlib versions, so a byte comparison passed on macOS and failed on the
    Linux CI runner against the same content. That is a gate that fails at random, which this
    repo has already learned trains people to re-run it -- and then a real failure gets re-run
    too.

    The wrapper is compared as text, and the payload DECOMPRESSED, where the tar is
    reproducible by construction. Which bytes zlib chose is not a fact about this repo.
    """
    try:
        head, body, tail = _split_collector(text)
        want_head, _, want_tail = _split_collector(COLLECTOR)
    except ValueError:
        return False
    if (head, tail) != (want_head, want_tail):
        return False
    try:
        return gzip.decompress(base64.b64decode(body)) == payload_tar(root)
    except (OSError, ValueError):
        return False


def compose(banner, parts):
    """One statement, the branches joined with UNION ALL, under the given banner."""
    return (banner.format(columns=", ".join(COLUMNS)) + "\n"
            + "\n\nUNION ALL\n\n".join(parts) + ";\n")


def flatten(sql):
    """Collapse SQL to one line for the pack, dropping -- comments first.

    THE ORDER MATTERS AND IS THE WHOLE POINT. A `--` comment runs to end of LINE, so
    flattening first and stripping never turns the first comment into a muzzle over
    everything after it. That shipped: four of the five pack queries returned zero rows,
    with no error, because the flattened string commented itself out after the first
    branch. Zero rows is what a clean Mac returns, so the pack looked like it worked.

    Quote-aware, because a literal could contain a double dash. None do today; a
    stripper that assumed so would be a trap for whoever adds one.
    """
    out, in_string, i = [], False, 0
    while i < len(sql):
        ch = sql[i]
        if in_string:
            out.append(ch)
            if ch == "'":
                in_string = sql[i + 1:i + 2] == "'"   # '' is an escaped quote
                if in_string:
                    out.append("'")
                    i += 1
            i += 1
            continue
        if ch == "'":
            in_string = True
            out.append(ch)
            i += 1
            continue
        if sql.startswith("--", i):
            while i < len(sql) and sql[i] != "\n":
                i += 1
            continue
        out.append(ch)
        i += 1
    flat = " ".join("".join(out).split())
    if "--" in flat:
        sys.exit(f"flatten left a comment in: {flat[:120]}")
    return flat


def frontmatter(text, path):
    """Read the `-- key: value` header. Absent keys are an error, not a default:
    a query with no declared cost silently escapes the performance gate."""
    fm = dict(re.findall(r"^--\s*([a-z-]+):\s*(.+?)\s*$", text, re.M))
    for key in ("name", "description", "cost", "platform"):
        if key not in fm:
            sys.exit(f"{path.name}: missing '-- {key}:' in frontmatter")
    if fm["cost"] not in ("fast", "slow", "expensive"):
        sys.exit(f"{path.name}: cost must be fast, slow or expensive, got {fm['cost']!r}")
    return fm


def body(text):
    """Everything that is not a leading frontmatter line."""
    lines = text.splitlines()
    start = 0
    for i, line in enumerate(lines):
        if line.strip() and not line.lstrip().startswith("--"):
            start = i
            break
    text = "\n".join(lines[start:]).strip()
    # A trailing semicolon here would end the composed query early and silently turn
    # the remainder into a second statement. osqueryi then emits two JSON documents
    # and every downstream parser sees only the first.
    return text.rstrip().rstrip(";").rstrip()


def main():
    check = "--check" in sys.argv
    files = sorted(QUERIES.glob("*.sql"))
    if not files:
        sys.exit("no queries found")

    inline, deep, pack = [], [], {}
    for path in files:
        text = path.read_text()
        fm = frontmatter(text, path)
        sql = body(text)
        pack[fm["name"]] = {
            "query": flatten(sql).rstrip(";") + ";",
            "interval": 3600,
            "platform": fm["platform"],
            "description": fm["description"],
        }
        if fm["cost"] == "expensive":
            print(f"  {path.name}: expensive, deep artifact only")
            deep.append(f"-- from {path.name}\n{sql}")
            continue
        inline.append(f"-- from {path.name}\n{sql}")

    composed = compose(BANNER, inline)
    conf = json.dumps({"queries": pack}, indent=2, sort_keys=True) + "\n"

    targets = {DIST / "discovery.sql": composed, DIST / "ai-discovery.conf": conf}

    # An empty deep artifact is NOT written. A file containing only a banner is not valid
    # SQL, and `osqueryi --json < banner-only-file` fails in a way that reads like a broken
    # install rather than like "there is nothing expensive to run". Absent is unambiguous,
    # and bin/discover --deep says so plainly. Any stale copy is removed below, and --check
    # treats a leftover as the drift it is.
    deep_path = DIST / "discovery-deep.sql"
    if deep:
        targets[deep_path] = compose(DEEP_BANNER, deep)
    if check:
        # A generated artifact that has drifted from its source is worse than no
        # generated artifact: consumers take dist/ at face value.
        stale = [p.name for p, want in targets.items()
                 if not p.exists() or p.read_text() != want]
        if not deep and deep_path.exists():
            stale.append(f"{deep_path.name} exists but no query declares itself expensive")
        collector_path = DIST / "jamf-collect.sh"
        if not collector_path.exists():
            stale.append(f"{collector_path.name} is missing")
        elif not collector_matches(collector_path.read_text(), ROOT):
            stale.append(f"{collector_path.name} does not carry the current bin/ and dist/")
        if stale:
            sys.exit(f"dist/ is stale: {', '.join(stale)}. Run tools/build.py.")
        print("dist/ is up to date")
        return

    DIST.mkdir(exist_ok=True)
    if not deep and deep_path.exists():
        deep_path.unlink()
        print(f"  removed {deep_path.relative_to(ROOT)} (nothing is expensive any more)")
    for path, content in targets.items():
        path.write_text(content)
        print(f"  wrote {path.relative_to(ROOT)} ({len(content.splitlines())} lines)")

    # LAST, and only now: it embeds the artifacts above, so it has to see their final bytes.
    collector_path = DIST / "jamf-collect.sh"
    collector_path.write_text(collector(ROOT))
    collector_path.chmod(0o755)
    print(f"  wrote {collector_path.relative_to(ROOT)} "
          f"({collector_path.stat().st_size // 1024} KB, embeds {len(PAYLOAD_FILES)} files)")


if __name__ == "__main__":
    main()
