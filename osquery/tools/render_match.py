#!/usr/bin/env python3
"""Render the catalog into SQL that matches agents ON the endpoint.

    dist/signatures.sql       a FRAGMENT: the signature table and the match, over an `ev`
                              CTE the caller supplies. bin/discover --names feeds it a payload
    dist/agents-darwin.sql    standalone: the composed enumeration wrapped in that match,
    dist/agents-linux.sql     one row per agent found. `sudo osqueryi --json < ...`
    dist/fleet-policies.yml   one Fleet policy per agent per platform, passing when absent

WHY A SECOND OUTPUT EXISTS. The enumeration queries carry no agent name, and matching
happens off the machine in bin/classify -- which is right for a collector and useless
for a Jamf Extension Attribute, a Fleet policy, or anyone with osqueryi and a question.
An Extension Attribute is one printed value a Smart Group matches on; a packed JSON
blob is not that. So the same catalog is rendered a second way, for readers that can
only run SQL. The enumeration stays primary and unchanged.

THE MATCH IS WRITTEN ONCE, OVER SIX-COLUMN ROWS. bin/classify matches rows of the
contract `kind, id, ver, loc, extra, perms`; so does the SQL below, whether the rows come
from json_each() over a payload or from the enumeration itself wrapped in a CTE. That is
what makes agreement with the classifier structural, and test/test_match_sql.py asserts
it per evidence row rather than per agent.

RENDERED, NEVER EDITED. The signature rows come out of bin/classify's own build_index,
so a value is matched the way the classifier matches it: exact where exact, a
front-anchored prefix where prefix, the classifier's compiled regex for the `~/` routes,
and a regex that encodes image_repo()'s four rules for container images. A route whose
match mode has no renderer here is a build failure, not a skipped route -- a route that
silently rendered nothing would be the dropped-`ext` bug again, matching nothing while the
output looked complete.

TWO FACTS ABOUT osqueryi's SQL SHAPE EVERYTHING BELOW (measured on 5.23.1):
  * regex_match() returns NULL on a miss, not '', so the test is IS NOT NULL -- and an
    INVALID pattern aborts the whole statement, exit 1, printing "[\n\n]". The join is a
    CASE so only one branch is ever evaluated, and every regex is compiled here first.
  * LIKE is case-insensitive. A prefix is substr(id, 1, length(v)) = v, never LIKE.

Needs PyYAML, like every tool that reads the catalog. tools/build.py does not, so it
learns these file names and leaves the checking to `python3 tools/render_match.py --check`.
"""
import hashlib
import importlib.machinery      # NOT implied by importlib.util; see test/lint.sh's check.
import importlib.util
import pathlib
import re
import sys

import build

ROOT = pathlib.Path(__file__).resolve().parent.parent  # osquery/, the binding
REPO = ROOT.parent  # the catalog and bin/classify sit at the repository root
DIST = ROOT / "dist"
CATALOG = REPO / "catalog" / "agents.yaml"

# The files this tool owns. tools/build.py reads this so its unknown-file check can tell
# "rendered here" from "nothing generates it"; tools/check_no_catalog.py reads it so the
# exception for identifiers in SQL is by NAME and a stray file cannot borrow it.
OUTPUTS = ("signatures.sql", "agents-darwin.sql", "agents-linux.sql", "fleet-policies.yml")

# A VALUES list this long is a catalog that has outgrown a literal table, and the day
# that happens the fragment should become something a reader can still open. The ceiling
# is a prompt, not a budget; `render_match.py --check` prints the current count.
MAX_SIGS = 400

PLATFORM_LABEL = {"darwin": "macOS", "linux": "Linux"}

BANNER = """-- GENERATED by tools/render_match.py. Do not edit.
-- Built from catalog/agents.yaml and catalog/routes.yaml (catalog sha256 {sha}).
-- To change it, edit the catalog and run tools/render_match.py.
--
-- This file matches ON the machine: it contains the agent names and identifiers from the
-- catalog, so osquery can answer "which agents are here" directly. It is what a Jamf
-- Extension Attribute, a Fleet policy and a one-off osqueryi run use. The other queries
-- in dist/ take the other route: they list what is installed and bin/classify matches it
-- later, off the machine. Both routes read the same catalog and find the same agents.
-- When the catalog changes, redeploy this file to pick up the change.
"""

FRAGMENT_NOTE = """--
-- This is a FRAGMENT of a query, not a complete one. It starts with a comma and ends after
-- the `hit` CTE. To use it, put `WITH ev AS (...)` before it and a SELECT after it:
--
--   WITH ev AS (SELECT ... AS kind, ... AS id, ... AS ver, ... AS loc, ... AS extra FROM ...)
--   <this file>
--   SELECT agent, name, max(ver) FROM hit GROUP BY agent;
--
-- `ev` must have the columns kind, id, ver, loc and extra, the same as the inventory rows.
-- bin/discover --names does this with an inventory file; dist/agents-<platform>.sql does it
-- with the live enumeration. `hit` has the columns agent, name, classification, superseded,
-- kind, id, ver, loc.
"""

AGENTS_NOTE = """--
-- PLATFORM: {platform}. Run this only on {platform}; see dist/discovery-{platform}.sql for why.
--
-- Returns one row per agent found: agent, name, classification, ver, rows, only_superseded.
-- `ver` is one of the version strings seen in that agent's evidence, not necessarily the
-- highest; some evidence, like a config directory, has no version. `only_superseded` is 1 when everything that matched is
-- an identifier the vendor has since replaced.
--
-- This query does not look at containers. A container query can hang, and the only way
-- to put a time limit on it is to kill the process, which bin/container-scan does. So an
-- agent that only ships as a container image ({image_only}) will not show up here. Use
-- `bin/discover --names --deep` for those.
--
-- An empty result means nothing matched in the places this query looks. Unlike the JSON
-- inventory, it has no way to say that part of the scan could not run.
"""

FLEET_HEAD = """# GENERATED by tools/render_match.py. Do not edit.
# Built from catalog/agents.yaml and catalog/routes.yaml (catalog sha256 {sha}).
# To change it, edit the catalog and run tools/render_match.py.
#
# One Fleet policy per agent, per platform. Load it with:
#   fleetctl apply -f dist/fleet-policies.yml
#
# A policy PASSES when the agent is not on the host and FAILS when it is. That way the
# failing-hosts list is the list of machines that have the agent, and Fleet's failure
# alerts fire when one appears. Change NOT EXISTS to EXISTS if you want it the other way.
#
# Each policy only reads the parts of the system where its agent can be found (Claude Code
# on macOS: home directories and npm packages), so it costs much less than a full scan.
# test/test_match_sql.py checks that these policies agree with bin/classify.
#
# Policies do not look at containers: a container query can hang and osqueryd cannot put a
# time limit on one query. Agents that only ship as container images have no policy
# here: {image_only}.
#
# Policies do not report versions. For versions, use bin/discover --write.
"""


def load_classify():
    """bin/classify as a module, so the signatures come out of its own build_index and
    its own regexes rather than a second copy of either."""
    spec = importlib.util.spec_from_loader(
        "classify", importlib.machinery.SourceFileLoader(
            "classify", str(REPO / "bin" / "classify")))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def catalog_sha(path=CATALOG):
    return hashlib.sha256(path.read_bytes()).hexdigest()[:12]


def image_regex(repo):
    """image_repo()'s four rules as one regex over a docker_images tags list.

    A tags column is comma-joined, so a repository is anchored at the start of the
    column or after a comma, and ends at ':' (the tag), ',' or the end. The implicit
    Docker Hub registry and `library/` are optional prefixes -- `library/` only for a
    repository with no '/', exactly where image_repo() strips it. Verified against
    paulgauthier/aider-fork (no), notpaulgauthier/aider (no), myreg:5000/x/y (no),
    docker.io/library/alpine:3 (yes for `alpine`), public.ecr.aws/docker/library/python
    (no for `python`): the same answers as the classifier, row for row.
    """
    hub = r"(?:(?:docker\.io|index\.docker\.io|registry-1\.docker\.io)/)?"
    lib = "" if "/" in repo else r"(?:library/)?"
    return r"(?:^|,)" + hub + lib + re.escape(repo) + r"(?::[^/,]*)?(?:,|$)"


def signatures(classify, catalog, registry):
    """Every signature as (agent, name, classification, kind, mode, value, superseded),
    sorted. `mode` is the SQL predicate: exact, prefix, path, image or tool-dir."""
    exact, prefix, glob = classify.build_index(catalog, registry)
    kind_of = {r: spec["kind"] for r, spec in registry.routes.items()}
    tool_dir_kinds = sorted({kind_of[r] for r, m in registry.match.items() if m == "tool-dir"})
    # The classifier's bridge: a pipx or uv directory named for a package is looked up as
    # a pypi value AND as an npm value, for agents that ship both. Rendered as a second
    # row per npm value rather than a second predicate, so the fragment stays one CASE.
    npm_routes = {r for r, m in registry.match.items()
                  if m == "exact" and kind_of[r] == "npm"}
    rows = set()

    def add(meta, kind, mode, value):
        rows.add((meta["id"], meta["name"], meta["classification"], kind, mode,
                  str(value), 1 if meta.get("superseded") else 0))

    for (route, value), meta in exact.items():
        if route in registry.retired:
            # A retired route's hit needs the classifier's corroboration step, which no
            # SQL below performs. No agent carries one today; refuse rather than render
            # a signature the classifier would decline.
            sys.exit(f"render_match: {route} is retired and still carries {value!r}; "
                     f"a retired route is not rendered")
        mode = registry.match[route]
        if mode == "exact":
            add(meta, kind_of[route], "exact", value)
            # A scoped name (`@openai/codex`) contains a '/', and the directory name the
            # bridge captures never can -- the classifier's lookup cannot meet it either.
            # Skipped so the fragment carries no signature nothing can satisfy.
            if route in npm_routes and "/" not in str(value):
                for kind in tool_dir_kinds:
                    add(meta, kind, "tool-dir", value)
        elif mode == "tool-dir":
            add(meta, kind_of[route], "tool-dir", value)
        elif mode == "exact-normalised":
            add(meta, kind_of[route], "image", image_regex(value))
        else:
            sys.exit(f"render_match: route {route} has match mode {mode!r}, which has "
                     f"no renderer here. Add one; do not skip the route.")
    for pre, route, meta in prefix:
        if registry.match[route] != "prefix":
            # A `*`-suffixed value on an exact route. The classifier also tries it
            # through the tool-dir bridge, which the equality predicate below cannot
            # express. Nothing in the catalog uses one; say so loudly if that changes.
            sys.exit(f"render_match: {route} carries the prefix value {pre + '*'!r} on a "
                     f"{registry.match[route]} route, which is not rendered")
        add(meta, kind_of[route], "prefix", pre)
    for pattern, route, meta in glob:
        add(meta, kind_of[route], "path", pattern.pattern)

    rows = sorted(rows)
    if len(rows) > MAX_SIGS:
        sys.exit(f"render_match: {len(rows)} signature rows; {MAX_SIGS} is where a VALUES "
                 f"table stops being something a reader can open. Rethink the shape.")
    # ONE AGENT PER SIGNATURE. The classifier gives a row to the first agent whose
    # signature it meets; a join reports every one. The two agree only while no value is
    # claimed twice, so a duplicate is refused here rather than discovered as a
    # disagreement in CI.
    seen = {}
    for agent, _, _, kind, mode, value, _ in rows:
        key = (kind, mode, value)
        if key in seen and seen[key] != agent:
            sys.exit(f"render_match: {kind} {mode} {value!r} is claimed by both "
                     f"{seen[key]} and {agent}; the classifier would pick one and this "
                     f"SQL would report both")
        seen[key] = agent
    for agent, _, _, kind, mode, value, _ in rows:
        if "\n" in value or "\r" in value:
            sys.exit(f"render_match: {agent}'s {kind} value contains a line break")
        if mode in ("path", "image"):
            try:
                re.compile(value)
            except re.error as exc:
                sys.exit(f"render_match: {agent}'s {kind} regex does not compile: {exc}")
    return rows


def sql_literal(s):
    """A SQLite string literal: quotes doubled, nothing else -- SQLite has no backslash
    escapes, so a regex passes through exactly as compiled above."""
    return "'" + s.replace("'", "''") + "'"


def fragment(sigs, tool_dir):
    """The `, sig(...) AS (VALUES ...), hit AS (...)` text. No banner, no statement."""
    values = ",\n  ".join(
        "(" + ",".join([sql_literal(agent), sql_literal(name), sql_literal(cls),
                        sql_literal(kind), sql_literal(mode), sql_literal(value),
                        str(sup)]) + ")"
        for agent, name, cls, kind, mode, value, sup in sigs)
    td = sql_literal(tool_dir)
    return (
        ", sig(agent, name, classification, kind, mode, value, superseded) AS (VALUES\n"
        f"  {values}),\n"
        "hit AS (SELECT s.agent, s.name, s.classification, s.superseded,\n"
        "               e.kind, e.id, e.ver, e.loc\n"
        "  FROM ev e JOIN sig s ON s.kind = e.kind AND CASE s.mode\n"
        "    WHEN 'exact'    THEN e.id = s.value\n"
        "    WHEN 'prefix'   THEN substr(e.id, 1, length(s.value)) = s.value\n"
        "    WHEN 'path'     THEN regex_match(e.id, s.value, 0) IS NOT NULL\n"
        "                      OR regex_match(e.loc, s.value, 0) IS NOT NULL\n"
        "    WHEN 'image'    THEN regex_match(e.id, s.value, 0) IS NOT NULL\n"
        f"    WHEN 'tool-dir' THEN regex_match(e.id, {td}, 1) = s.value\n"
        f"                      OR regex_match(e.loc, {td}, 1) = s.value\n"
        "    ELSE 0 END)\n")


# The version is ONE OF THOSE SEEN: max() over strings is alphabetical. Container rows are
# excluded because their `ver` is the container state, not a version.
AGENTS_SELECT = ("SELECT agent, name, classification,\n"
                 "       max(CASE WHEN kind = 'container' THEN '' ELSE ver END) AS ver,\n"
                 "       count(*) AS rows,\n"
                 "       min(superseded) AS only_superseded\n"
                 "  FROM hit GROUP BY agent ORDER BY name;\n")


def ev_cte(parts):
    """`WITH ev AS (...)` over query bodies joined with UNION ALL."""
    return "WITH ev AS (\n" + "\n\nUNION ALL\n\n".join(parts) + "\n)\n"


def image_only_agents(sigs, inline_kinds):
    """Agents none of whose signatures can be met by a non-expensive branch."""
    reachable = {a for a, _, _, k, _, _, _ in sigs if k in inline_kinds}
    return sorted({a for a, *_ in sigs} - reachable)


def policy(agent, plat, sigs, parts, tool_dir):
    """One Fleet policy document. `parts` are the branches this agent needs."""
    sql = ev_cte(parts) + fragment(sigs, tool_dir) + \
        "SELECT 1 WHERE NOT EXISTS (SELECT 1 FROM hit);"
    name = agent["name"]
    kinds = ", ".join(sorted({k for _, _, _, k, _, _, _ in sigs}))
    return (
        "---\n"
        "apiVersion: v1\n"
        "kind: policy\n"
        "spec:\n"
        f"  name: \"AI agent: {name} ({PLATFORM_LABEL[plat]})\"\n"
        f"  platform: {plat}\n"
        f"  description: \"Passes when no evidence of {name} is on the host. Evidence "
        f"kinds read: {kinds}. Generated by tools/render_match.py from "
        f"catalog/agents.yaml; a failing host is one that carries it.\"\n"
        f"  resolution: \"A failing host carries {name}. Collect bin/discover --write "
        f"for the evidence rows.\"\n"
        "  query: |\n"
        f"    {build.flatten(sql)}\n")


def targets():
    """Every rendered file as {path: text}. One read of everything, one render."""
    classify = load_classify()
    catalog = classify.load_catalog(CATALOG)
    registry = classify.Registry(classify.load_routes())
    sigs = signatures(classify, catalog, registry)
    tool_dir = classify.TOOL_DIR.pattern
    sha = catalog_sha()
    frag = fragment(sigs, tool_dir)
    qs = [q for q in build.queries() if not q["expensive"]]
    inline_kinds = {k for q in qs for k in q["kinds"]}
    image_only = image_only_agents(sigs, inline_kinds)
    image_only_text = ", ".join(image_only) if image_only else "none today"

    out = {DIST / "signatures.sql": BANNER.format(sha=sha) + FRAGMENT_NOTE + frag}

    platforms = sorted({p for q in qs for p in q["platforms"]})
    for plat in platforms:
        parts = [f"-- from {q['path'].name}\n{q['sql']}" for q in qs if plat in q["platforms"]]
        out[DIST / f"agents-{plat}.sql"] = (
            BANNER.format(sha=sha)
            + AGENTS_NOTE.format(platform=plat, image_only=image_only_text)
            + ev_cte(parts) + frag + AGENTS_SELECT)

    docs = [FLEET_HEAD.format(sha=sha, image_only=image_only_text)]
    for agent in catalog["agents"]:
        for plat in agent["platforms"]:
            if plat not in platforms:
                continue
            # Only the signatures this platform's branches can meet: a macOS policy does
            # not carry deb values, and a policy reads only the files whose kinds its
            # signatures name. What is left out is exactly what could never match here.
            plat_kinds = {k for q in qs if plat in q["platforms"] for k in q["kinds"]}
            mine = [s for s in sigs if s[0] == agent["id"] and s[3] in plat_kinds]
            kinds = {s[3] for s in mine}
            parts = [f"-- from {q['path'].name}\n{q['sql']}" for q in qs
                     if plat in q["platforms"] and kinds & set(q["kinds"])]
            if not parts:
                continue
            docs.append(policy(agent, plat, mine, parts, tool_dir))
    out[DIST / "fleet-policies.yml"] = "".join(docs)

    for path in out:
        if path.name not in OUTPUTS:
            sys.exit(f"render_match: {path.name} is rendered but not in OUTPUTS")
    return out


def check():
    """Stale or missing rendered files, as messages. Empty means up to date."""
    return [f"{p.name} is stale or missing" for p, want in targets().items()
            if not p.exists() or p.read_text() != want]


def write():
    DIST.mkdir(exist_ok=True)
    for path, content in targets().items():
        path.write_text(content)
        print(f"  wrote {path.relative_to(ROOT)} ({len(content.splitlines())} lines)")


def main():
    if "--check" in sys.argv:
        stale = check()
        if stale:
            sys.exit(f"rendered match SQL is stale: {', '.join(stale)}. "
                     f"Run {pathlib.Path(__file__).resolve().relative_to(REPO)}.")
        print(f"rendered match SQL is up to date ({len(OUTPUTS)} files)")
        return
    write()


if __name__ == "__main__":
    main()
